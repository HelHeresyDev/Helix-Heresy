const { test, expect } = require('@playwright/test');
const { visit } = require('./helpers/multi-city-visit');
const { sources } = require('./helpers/regional-government-source');
test.setTimeout(900000);
const snapshot = page => page.evaluate(() => window.helixHeresyDebug.regionalGovernmentSnapshot());
const tick = (page, n) => page.evaluate(n => window.helixHeresyDebug.advanceCityRuleForTest(n), n);
for (const renderer of ['dom', 'canvas']) test(`${renderer}: attended foreign designation and two independently supplied original city accounts`, async ({ page }) => {
  const errors = []; page.on('pageerror', e => errors.push(e.message)); page.on('dialog', d => d.accept());
  page.on('console', m => { if (m.text().startsWith('multi-city:')) console.log(m.text()); });
  await visit(page, renderer);
  const world = await page.evaluate(() => localStorage.getItem('helix-heresy-v2-world:lifecycle-world'));
  const home = await page.evaluate(() => window.helixHeresyDebug.cityRuleSnapshot());
  expect(home.saved.status).toBe('established'); expect(home.saved.report.accomplishment).toBeTruthy();
  const original = sources();
  await page.locator('[data-workspace-tab="visits"]').click();
  const panel = page.locator('[data-regional-governments]');
  expect(await page.evaluate(s => { const d = window.helixHeresyDebug;
    return d.setForeignCivicBargainTestSource(s.succession) && d.setRegionalGovernmentTestSources('b', s);
  }, original)).toBe(true);
  await panel.locator('[data-government-action="request"]').click(); await tick(page, 30);
  let s = await snapshot(page); expect(s.gates).toHaveLength(1);
  expect(s.gates[0].saved.succession.phase, JSON.stringify(s)).toBe('ready');
  expect(s.gates[0].saved.rule).toBeNull();
  const ids = s.gates[0].saved.succession.leaders.map(a => a.id);
  const balance = s.gates[0].work;
  await panel.locator('[data-government-action="hear"]').click(); await tick(page, 70);
  expect((await snapshot(page)).gates[0].saved.succession.job.progress).toBe(70);
  await page.reload(); await page.locator('#loadLastSaveBtn').click(); await page.locator('[data-workspace-tab="visits"]').click();
  await tick(page, 110); s = await snapshot(page); expect(s.gates[0].saved.succession.phase, JSON.stringify(s)).toBe('offered');
  expect(balance - s.gates[0].work).toBe(180);
  await panel.locator('[data-government-action="sign"]').click();
  expect(await page.evaluate(() => window.helixHeresyDebug.regionalGovernmentAction('handover'))).toBe(false);
  await panel.locator('[data-government-action="deliver"]').click();
  for (const id of [...ids, s.gates[0].bargain.defender.id]) {
    expect(await page.evaluate(id => window.helixHeresyDebug.regionalGovernmentAction('agree', id), id)).toBe(true); await tick(page, 60);
  }
  await panel.locator('[data-government-action="handover"]').click(); await tick(page, 180);
  s = await snapshot(page); expect(s.gates[0].saved.succession.phase).toBe('transferred'); expect(s.gates[0].saved.rule).toBeTruthy();
  expect(s.gates[0].saved.succession.provision.stock).toBe(18);
  console.log(`multi-city: ${renderer} actual foreign handover complete`);
  await panel.locator('[data-government-action="operate"]').click(); await tick(page, 3600);
  await panel.locator('[data-government-action="report"]').click(); const dated = (await snapshot(page)).gates[0].saved.knowledge;
  await tick(page, 3 * 86400);
  s = await snapshot(page); const second = s.gates[0].saved;
  expect(second.rule.status, JSON.stringify({ saved: second.rule, context: s.gates[0].context })).toBe('established');
  expect(second.knowledge).toEqual(dated);
  const first = await page.evaluate(() => window.helixHeresyDebug.cityRuleSnapshot());
  expect(first.saved.id).toBe(home.saved.id); expect(first.saved.status).toBe('established');
  expect(first.saved.report).toEqual(home.saved.report); expect(first.saved.energy).toBeLessThan(home.saved.energy);
  expect(first.saved.farms[0].drivers + 1).toBe(6); expect(second.rule.farms[0].drivers).toBe(6);
  expect(second.succession.leaders.map(a => a.id)).toEqual(ids);
  await panel.locator('[data-government-action="report"]').click(); s = await snapshot(page);
  expect(s.gates[0].saved.knowledge.report.accomplishment).toBeTruthy();
  await page.locator('[data-durable-supremacy] [data-supremacy-action="review"]').click();
  const reviewed = await page.evaluate(() => window.helixHeresyDebug.supremacySnapshot());
  expect(reviewed.public.review.evidence.filter(r => r.id.startsWith('city-rule:'))).toHaveLength(2);
  expect(reviewed.saved.phase).not.toBe('qualified');
  expect(await page.evaluate(() => window.helixHeresyDebug.cityRuleAction('report'))).toBe(false);
  const saved = s.gates[0].saved; await page.reload(); await page.locator('#loadLastSaveBtn').click();
  expect((await snapshot(page)).gates[0].saved).toEqual(saved);
  expect(await page.evaluate(() => window.helixHeresyDebug.validateMapScene())).toEqual([]);
  expect(await page.evaluate(() => localStorage.getItem('helix-heresy-v2-world:lifecycle-world'))).toBe(world);
  expect(errors).toEqual([]);
});
