test('Canvas crossing elaborates once, preserves the first station and property, and physically depletes separate finite same-hex stone', async ({ page }) => {
  const f = await setup(page, 'canvas', true), before = await survey(page);
  expect(await act(page, 'exploreAdjoining')).toBe(false); expect((await snap(page)).site.extension).toBeUndefined();
  await page.getByRole('button', { name: 'Walk to eastern wilderness edge', exact: true }).click(); await finish(page);
  expect((await snap(page)).cell).toEqual(f.seam);
  await page.getByRole('button', { name: 'Explore adjoining local ground', exact: true }).click();
  let s = await snap(page); expect(s.cell).toEqual(f.seam); expect(s.site.extension.discovery).toBeNull();
  await finish(page); s = await snap(page); const ext = s.site.extension;
  expect(s.cell).toEqual(f.entry); expect(ext.materialized).toBe(true); expect(ext.discovery.baseline.cells.length).toBeGreaterThan(150);
  expect(ext.context.strategicCellId).toBe(s.site.context.strategicCellId); expect(ext.context.worldId).toBe(s.site.context.worldId);
  expect(ext.context.siteId).not.toBe(s.site.context.siteId); expect(s.site.discovery.baseline).toEqual(f.original);
  expect(s.site.beasts.actors).toEqual(before.excursion.wilderness.beasts.actors);
  expect(await page.evaluate(() => window.helixHeresyDebug.fieldStationAction('register'))).toBe(false);
  expect(await page.evaluate(() => window.helixHeresyDebug.fieldStationSnapshot().saved.site)).toEqual(f.station);
  const node = await page.evaluate(() => window.helixHeresyDebug.surfaceStoneSnapshot().site.nodes[0]); expect(node).toBeTruthy();
  expect(node.cell.x).toBeGreaterThanOrEqual(f.entry.x);
  const work = ext.discovery.baseline.cells.find(c => Math.abs(c.x - node.cell.x) + Math.abs(c.y - node.cell.y) === 1);
  expect(work).toBeTruthy(); await move(page, work); // Inspect the actual face at arm's reach, not from the patch entrance.
  expect(await page.evaluate(id => window.helixHeresyDebug.startSurfaceStoneWork('inspect', id), node.id)).toBe(true); await finish(page);
  expect(await page.evaluate(id => window.helixHeresyDebug.startSurfaceStoneWork('recover', id), node.id)).toBe(true);
  await advance(page, 30); const partial = await page.evaluate(() => window.helixHeresyDebug.surfaceStoneSnapshot().tasks.find(t => t.data?.stoneWork).data.stoneWork.progress);
  await reload(page, 'canvas'); expect(await page.evaluate(() => window.helixHeresyDebug.surfaceStoneSnapshot().tasks.find(t => t.data?.stoneWork).data.stoneWork.progress)).toBe(partial);
  await finish(page); const stone = await page.evaluate(() => window.helixHeresyDebug.surfaceStoneSnapshot());
  const receipt = stone.site.nodes.find(n => n.id === node.id).receipts.at(-1), output = stone.stacks.find(i => i.id === receipt.outputId);
  expect(stone.site.nodes.find(n => n.id === node.id).remaining).toBe(node.remaining - 1);
  expect(output).toMatchObject({ key: 'stoneBlocks', quantity: 1, unitMassKg: 8, unitVolumeL: 5, carriedBy: '' });
  expect(output.cell.x).toBeGreaterThanOrEqual(f.entry.x); const savedNodes = stone.site.nodes;
  await move(page, s.site.entry); await reload(page, 'canvas');
  expect(await page.evaluate(() => window.helixHeresyDebug.surfaceStoneSnapshot().site)).toEqual(f.stone);
  expect(await page.evaluate(() => window.helixHeresyDebug.fallenTimberSnapshot().site)).toEqual(f.timber);
  expect((await survey(page)).stacks.find(i => i.id === f.property)).toMatchObject({ quantity: 1, carriedBy: '' });
  await move(page, f.entry); const again = await page.evaluate(() => window.helixHeresyDebug.surfaceStoneSnapshot());
  expect(again.site.nodes).toEqual(savedNodes); expect(again.site.nodes.find(n => n.id === node.id).receipts.filter(r => r.action === 'recover')).toHaveLength(1);
  expect(again.stacks.find(i => i.id === output.id)).toMatchObject({ quantity: 1, cell: output.cell });
  expect((await snap(page)).site.extension.discovery.baseline).toEqual(ext.discovery.baseline);
  const after = await survey(page); expect(after.excursion.carrier.driver.id).toBe(before.excursion.carrier.driver.id);
  expect(after.excursion.carrier.vehicle.fuelKm).toBe(before.excursion.carrier.vehicle.fuelKm);
  expect(await page.evaluate(() => window.helixHeresyDebug.validateMapScene())).toEqual([]); expect(f.errors).toEqual([]);
});
test('DOM the same wounded regional beast pursues across an unwarded seam without resetting identity memory or attack cooldown', async ({ page }) => {
  const f = await setup(page, 'dom'); await move(page, f.seam);
  const original = await page.evaluate(({ seam, beast }) => {
    const d = window.helixHeresyDebug, s = d.exportSurveyExpeditionTestState(), w = s.penalFlights.assistance.cityApproach.gates.find(g => g.cityId === 'b').foreignSurvey.wilderness;
    // One explicit pre-existing regional encounter, not an extension spawn.
    Object.assign(beast, { roomId: w.roomId, health: 31, nextMoveAt: s.clock + 3, nextAttackAt: s.clock + 600,
      provokedUntil: s.clock + 90, targetId: 'scientist', lastTarget: seam, rememberedUntil: s.clock + 30 });
    w.beasts = { ...window.HelixWildernessBeasts.defaultState(), materialized: true, siteId: w.destination.id, actors: [beast], lastAt: s.clock };
    d.importSurveyExpeditionTestState(s); return beast;
  }, { seam: f.seam, beast: Beasts.actor('beast:rimefang-pack', 'original-seam-beast', { ...f.seam, x: f.seam.x - 2 }, 'original-regional-population', 0) });
  expect(await act(page, 'exploreAdjoining')).toBe(true); await finish(page);
  await move(page, { ...f.entry, x: f.entry.x + 4 }); await advance(page, 10);
  let s = await snap(page), beast = s.site.beasts.actors[0];
  expect(s.site.beasts.actors).toHaveLength(1); expect(beast).toMatchObject({ id: original.id, health: 31, populationId: original.populationId, nextAttackAt: original.nextAttackAt });
  expect(beast.mapCell.x).toBeGreaterThanOrEqual(f.entry.x); expect(beast.behavior).toBe('pursue'); expect(beast.rememberedUntil).toBeGreaterThan(s.clock);
  const persisted = { cell: beast.mapCell, memory: beast.rememberedUntil, attack: beast.nextAttackAt };
  await reload(page, 'dom'); s = await snap(page); beast = s.site.beasts.actors[0];
  expect(beast.mapCell).toEqual(persisted.cell); expect(beast.rememberedUntil).toBe(persisted.memory); expect(beast.nextAttackAt).toBe(persisted.attack);
  // The pursuer now physically occupies the direct western withdrawal line.
  // Sidestep on clear adjoining ground first instead of waiting against its
  // body until its real attack cooldown expires.
  await move(page, { ...f.entry, x: f.entry.x + 4, y: s.site.extension.bounds.y });
  expect(await act(page, 'withdraw')).toBe(true); await finish(page); expect((await survey(page)).context.atFieldEntry).toBe(true);
  s = await snap(page); expect(s.site.beasts.actors[0].mapCell.x).toBeGreaterThanOrEqual(s.site.bounds.x);
  const known = s.knowledge; await advance(page, 20); expect((await snap(page)).knowledge).toEqual(known);
  expect((await snap(page)).site.beasts.actors.map(a => a.id)).toEqual([original.id]);
  expect(await page.evaluate(() => window.helixHeresyDebug.validateMapScene())).toEqual([]); expect(f.errors).toEqual([]);
});
