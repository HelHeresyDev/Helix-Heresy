const snap = page => page.evaluate(() => window.helixHeresyDebug.foreignWildernessSnapshot());
const survey = page => page.evaluate(() => window.helixHeresyDebug.foreignSurveySnapshot());
const act = (page, action) => page.evaluate(action => window.helixHeresyDebug.foreignSurveyAction(action), action);
const advance = (page, n) => page.evaluate(n => window.helixHeresyDebug.advanceAdjoiningWildernessForTest(n), n);
async function finish(page) {
  for (let n = 0; n < 25; n++) {
    const s = await snap(page); if (!s.tasks.length) return;
    expect(s.tasks[0].reason, JSON.stringify(s.tasks[0])).toBe('');
    await advance(page, Math.max(1, s.tasks[0].dueAt - s.clock + 1));
  }
  throw new Error(`Physical adjoining-ground work did not finish: ${JSON.stringify((await snap(page)).tasks)}`);
}
async function move(page, cell) {
  const s = await snap(page); if (JSON.stringify(s.cell) === JSON.stringify(cell)) return;
  expect(await page.evaluate(({ room, cell }) => Boolean(window.helixHeresyDebug.startScientistMove(room, { toCell: cell, allowMultiRoom: true, urgent: true })),
    { room: s.site.roomId, cell })).toBe(true); await finish(page);
}
async function reload(page, renderer) {
  await page.reload(); await page.locator('#loadLastSaveBtn').click(); await page.evaluate(r => window.helixHeresyDebug.setMapRenderer(r), renderer);
  const tab = page.locator('[data-workspace-tab="visits"]'); if (await tab.getAttribute('aria-current') !== 'page') await tab.click();
}
async function setup(page, renderer, tools = false) {
  const errors = []; page.on('pageerror', e => errors.push(e.message)); page.on('dialog', d => d.accept());
  await startLifecycleRun(page, `adjoining-ground-${renderer}`);
  const city = { cityId: 'b', assetId: 'population:b', currentPopulation: 100, physicalCondition: 'intact', services: { transport: 'functional' } };
  const source = { cityId: 'b', administrationId: 'admin:b', worksId: 'works:b', charterId: 'charter:b', populationSourceId: city.assetId,
    cellId: 'planet-cell:00001', name: 'Birch Ground', placeId: 'foreign-survey:b' };
  const carrier = Carrier.fromWorld({ strategicPlayableSettlementState: { cityRows: [city] }, cityGovernments: {
    governments: [{ cityId: 'b', roleAssignments: { publicWorksAndProvisioning: 'works:b' }, institutions: [{ id: 'works:b', capacityBand: 'functional' }] }] } }, 'b', 0);
  const f = await page.evaluate(({ source, carrier, renderer, tools }) => {
    const d = window.helixHeresyDebug; d.setMapRenderer(renderer);
    const context = { worldId: 'lifecycle-world', siteId: source.placeId, strategicCellId: source.cellId, seed: 'adjoining-test',
      truth: { potentialPermille: { constructionStone: 1000, timberFiber: 1000 }, typicalDepth: { constructionStone: 'exposed' }, surfaceAccessibilityPermille: 1000 } };
    if (!d.configureFieldStationMaintenanceTest({ source, carrier, context, wilderness: { origin: { id: source.cellId, neighborIds: ['planet-cell:00002'] },
      candidates: [{ id: 'planet-cell:00002', surfaceClass: 'land', slopePercent: 10, temperatureC: 18, precipitationMm: 100, biomeLabel: 'Woodland' }], occupied: [], context } })) return null;
    if (!d.fieldStationAction('register')) return null;
    // Explicit finite initial tools and loose property. New terrain and stone
    // sources are generated by the production geography, not this fixture.
    const property = d.configureHiddenWorkshopTest({ carryTools: tools ? ['masonryHammer', 'stoneChisel'] : [], supplies: { lumber: 1 } })[0];
    if (tools) { const s = d.exportSurveyExpeditionTestState(); s.scientist.skills.materialsScience = { ...(s.scientist.skills.materialsScience || {}), xp: 100000 }; d.importSurveyExpeditionTestState(s); }
    const w = d.foreignWildernessSnapshot().site;
    return { property, station: d.fieldStationSnapshot().saved.site, original: w.discovery.baseline,
      stone: d.surfaceStoneSnapshot().site, timber: d.fallenTimberSnapshot().site,
      seam: { x: w.bounds.x + w.bounds.width - 1, y: w.entry.y, z: w.entry.z }, entry: { x: w.bounds.x + w.bounds.width, y: w.entry.y, z: w.entry.z } };
  }, { source, carrier, renderer, tools });
  expect(f).toBeTruthy(); const tab = page.locator('[data-workspace-tab="visits"]'); if (await tab.getAttribute('aria-current') !== 'page') await tab.click();
  return { ...f, errors };
}
