// Publish the approved numeric authoring data for the dependency-free browser.
// Generated data is not a second hand-maintained balance authority.
const fs = require('node:fs');
const path = require('node:path');
const life = require('./creature-lifecycle-data');
const ecology = require('./creature-ecology-design');
const data = {
  lifecycle: Object.fromEntries(life.profiles.map(p => [p.id, p])),
  rates: Object.fromEntries(ecology.rateProfiles.map(p => [p.id, p])),
  ledgers: ecology.rateLedgers,
  antagonisms: ecology.antagonisms,
  roles: Object.fromEntries(ecology.rows.map(p => [p.id, p.role]))
};
const output = '// Generated by scripts/build-creature-biology.js; edit the authored lifecycle/ecology sources.\n' +
  '(function (root) {\n  const data = ' + JSON.stringify(data, null, 2) + ';\n' +
  '  if (typeof module === "object" && module.exports) module.exports = data;\n' +
  '  root.HelixCreatureBiology = data;\n})(globalThis);\n';
fs.writeFileSync(path.resolve(__dirname, '../creature-biology.js'), output);
process.stdout.write(`Published ${life.profiles.length} creature life histories and ecological rate profiles.\n`);
